"""Vercel serverless endpoint for downloadable meeting reports."""
from http.server import BaseHTTPRequestHandler
from datetime import datetime
from html import escape
from io import BytesIO
import json

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable


def json_response(handler, status, payload):
    body = json.dumps(payload).encode("utf-8")
    handler.send_response(status)
    handler.send_header("Content-Type", "application/json; charset=utf-8")
    handler.send_header("Content-Length", str(len(body)))
    handler.end_headers()
    handler.wfile.write(body)


class handler(BaseHTTPRequestHandler):
    def do_POST(self):
        try:
            length = int(self.headers.get("Content-Length", "0"))
            if length <= 0 or length > 1_000_000:
                json_response(self, 413, {"error": "Report text is empty or too large."})
                return

            payload = json.loads(self.rfile.read(length).decode("utf-8"))
            report_text = str(payload.get("text", "")).strip()
            if not report_text:
                json_response(self, 400, {"error": "There is no result to export yet."})
                return

            buffer = BytesIO()
            page_width, _ = letter
            doc = SimpleDocTemplate(
                buffer,
                pagesize=letter,
                rightMargin=0.65 * inch,
                leftMargin=0.65 * inch,
                topMargin=0.65 * inch,
                bottomMargin=0.65 * inch,
                title="Meeting Decisions Report",
                author="Board Meeting Decisions Tracker",
            )
            styles = getSampleStyleSheet()
            title_style = ParagraphStyle(
                "ReportTitle", parent=styles["Title"], fontName="Helvetica-Bold",
                fontSize=19, leading=24, alignment=0, textColor=colors.HexColor("#172554"),
                spaceAfter=8,
            )
            body_style = ParagraphStyle(
                "ReportBody", parent=styles["BodyText"], fontName="Helvetica",
                fontSize=10.5, leading=15, spaceAfter=5, wordWrap="CJK",
            )
            meta_style = ParagraphStyle(
                "ReportMeta", parent=styles["Normal"], fontSize=8.5,
                textColor=colors.HexColor("#64748b"), spaceAfter=12,
            )
            story = [
                Paragraph("Meeting Decisions Report", title_style),
                Paragraph("Generated on: " + datetime.now().strftime("%B %d, %Y at %I:%M %p"), meta_style),
                HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=16),
            ]
            for line in report_text.splitlines():
                safe_line = escape(line.strip()) if line.strip() else "&#160;"
                story.append(Paragraph(safe_line, body_style))
            def draw_footer(canvas, document):
                canvas.saveState()
                canvas.setFont("Helvetica-Oblique", 8)
                canvas.setFillColor(colors.HexColor("#64748b"))
                canvas.drawString(0.65 * inch, 0.35 * inch, "Generated by Board Meeting Decisions Tracker")
                canvas.drawRightString(page_width - 0.65 * inch, 0.35 * inch, "Page " + str(document.page))
                canvas.restoreState()

            doc.build(story, onFirstPage=draw_footer, onLaterPages=draw_footer)
            pdf_bytes = buffer.getvalue()
            self.send_response(200)
            self.send_header("Content-Type", "application/pdf")
            self.send_header("Content-Disposition", 'attachment; filename="Meeting-Decisions.pdf"')
            self.send_header("Content-Length", str(len(pdf_bytes)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(pdf_bytes)
        except Exception as exc:
            print("PDF generation failed:", repr(exc))
            json_response(self, 500, {"error": "Could not generate the PDF. Please try again."})

    def log_message(self, format, *args):
        print("PDF API:", format % args)
